"use server";

// Admin actions. Each one checks the admin again (actions are public endpoints), and the database's
// row-level security enforces the same rule underneath.
import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";
import { requireAdmin } from "@/lib/admin/guard";
import type { ImportRow } from "@/lib/admin/eventbrite";
import { sendWelcomeEmails, type WelcomeTarget } from "@/lib/email/welcome";
import { rows } from "@/lib/rows";
import { formatWhen, localToIso } from "@/lib/time";

const QUEST_TYPES = ["making", "tasting", "tradition", "performance", "social", "discovery", "puzzle", "multi_stop"];

function text(form: FormData, key: string, max = 200): string | null {
  const v = String(form.get(key) ?? "").trim().slice(0, max);
  return v === "" ? null : v;
}
function int(form: FormData, key: string): number | null {
  const v = text(form, key, 12);
  if (v === null) return null;
  const n = Number(v);
  return Number.isFinite(n) ? Math.round(n) : null;
}
function back(path: string, msg: string): never {
  redirect(`${path}${path.includes("?") ? "&" : "?"}msg=${encodeURIComponent(msg)}`);
}

// ---------------------------------------------------------------------------------------------
// Sessions
// ---------------------------------------------------------------------------------------------
function sessionFields(form: FormData) {
  const startsAt = localToIso(String(form.get("starts_at") ?? ""));
  let revealAt = localToIso(String(form.get("revealed_at") ?? ""));
  // No reveal time given: 48 hours before the start (docs/game-design.md, pre-game reveal).
  if (!revealAt && startsAt) revealAt = new Date(new Date(startsAt).getTime() - 48 * 3600 * 1000).toISOString();
  return {
    number: int(form, "number"),
    neighborhood: text(form, "neighborhood", 80),
    starts_at: startsAt,
    start_location: text(form, "start_location", 200),
    revealed_at: revealAt,
    is_finals: form.get("is_finals") === "on",
  };
}

export async function createSession(form: FormData) {
  const { supabase } = await requireAdmin();
  const seasonId = text(form, "season_id", 64);
  const fields = sessionFields(form);
  if (!seasonId || fields.number === null || fields.number < 1) back("/admin", "Pick a season and a session number.");
  const { data, error } = await supabase.from("session").insert({ season_id: seasonId, ...fields }).select("id").single();
  if (error || !data) back("/admin", error?.code === "23505" ? "That season already has a session with that number." : "Couldn't create the session.");
  revalidatePath("/admin");
  redirect(`/admin/sessions/${(data as { id: string }).id}?msg=${encodeURIComponent("Session created. Add its quests below.")}`);
}

export async function updateSession(form: FormData) {
  const { supabase } = await requireAdmin();
  const id = text(form, "id", 64);
  if (!id) back("/admin", "Missing session.");
  const fields = sessionFields(form);
  const { number: _n, ...rest } = fields;
  const { error } = await supabase.from("session").update(rest).eq("id", id);
  if (error) back(`/admin/sessions/${id}`, "Couldn't save the session.");
  revalidatePath(`/admin/sessions/${id}`);
  back(`/admin/sessions/${id}`, "Saved.");
}

// ---------------------------------------------------------------------------------------------
// Quests (codes are generated by the database)
// ---------------------------------------------------------------------------------------------
export async function createQuest(form: FormData) {
  const { supabase } = await requireAdmin();
  const sessionId = text(form, "session_id", 64);
  const title = text(form, "title", 120);
  const type = text(form, "type", 20);
  if (!sessionId || !title || !type || !QUEST_TYPES.includes(type)) back(`/admin/sessions/${sessionId}`, "A quest needs a title and a type.");
  const isHidden = form.get("is_hidden") === "on";
  const isJudged = form.get("is_judged") === "on";
  const xp = int(form, "xp") ?? (isHidden ? 30 : 25); // docs/game-design.md section 9
  const feeDollars = text(form, "host_fee", 12);
  const { error } = await supabase.from("quest").insert({
    session_id: sessionId,
    title,
    type,
    stop_number: isHidden || isJudged ? null : int(form, "stop_number"),
    xp: Math.max(1, xp),
    is_hidden: isHidden,
    is_judged: isJudged,
    host_id: text(form, "host_id", 64),
    max_points: int(form, "max_points"),
    host_fee_cents: feeDollars ? Math.round(Number(feeDollars) * 100) || null : null,
  });
  if (error) back(`/admin/sessions/${sessionId}`, "Couldn't add the quest.");
  revalidatePath(`/admin/sessions/${sessionId}`);
  back(`/admin/sessions/${sessionId}`, `Added "${title}".`);
}

export async function updateQuest(form: FormData) {
  const { supabase } = await requireAdmin();
  const id = text(form, "id", 64);
  const sessionId = text(form, "session_id", 64);
  const title = text(form, "title", 120);
  const type = text(form, "type", 20);
  if (!id || !title || !type || !QUEST_TYPES.includes(type)) back(`/admin/sessions/${sessionId}`, "A quest needs a title and a type.");
  const isHidden = form.get("is_hidden") === "on";
  const isJudged = form.get("is_judged") === "on";
  const feeDollars = text(form, "host_fee", 12);
  const { error } = await supabase
    .from("quest")
    .update({
      title,
      type,
      stop_number: isHidden || isJudged ? null : int(form, "stop_number"),
      xp: Math.max(1, int(form, "xp") ?? (isHidden ? 30 : 25)),
      is_hidden: isHidden,
      is_judged: isJudged,
      host_id: text(form, "host_id", 64),
      max_points: int(form, "max_points"),
      host_fee_cents: feeDollars ? Math.round(Number(feeDollars) * 100) || null : null,
    })
    .eq("id", id);
  revalidatePath(`/admin/sessions/${sessionId}`);
  // XP already earned for this quest stays as it was: progress only goes up.
  back(`/admin/sessions/${sessionId}`, error ? "Couldn't save the quest." : `Saved "${title}".`);
}

export async function deleteQuest(form: FormData) {
  const { supabase } = await requireAdmin();
  const id = text(form, "id", 64);
  const sessionId = text(form, "session_id", 64);
  const { error } = await supabase.from("quest").delete().eq("id", id);
  // Completed quests can't be deleted (a completion references them): progress only goes up.
  if (error) back(`/admin/sessions/${sessionId}`, "A team already completed that quest, so it stays.");
  revalidatePath(`/admin/sessions/${sessionId}`);
  back(`/admin/sessions/${sessionId}`, "Quest removed.");
}

