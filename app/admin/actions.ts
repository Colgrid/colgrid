export type ImportResult =
  | { ok: true; players_created: number; players_existing: number; tickets_added: number; tickets_existing: number; skipped: { row: number; email: string | null; reason: string }[] }
  | { ok: false; error: string };

export async function importPlayers(sessionId: string, importRows: ImportRow[]): Promise<ImportResult> {
  const { supabase } = await requireAdmin();
  if (!sessionId || !Array.isArray(importRows) || importRows.length === 0) return { ok: false, error: "Pick a session and a file first." };
  if (importRows.length > 2000) return { ok: false, error: "That's more than 2,000 rows. Split the file." };
  const clean = importRows.map((r) => ({
    email: String(r.email ?? "").slice(0, 254),
    name: String(r.name ?? "").slice(0, 120),
    coming_with: r.coming_with ? String(r.coming_with).slice(0, 60) : null,
    order_ref: r.order_ref ? String(r.order_ref).slice(0, 60) : null,
    ticket_type: r.ticket_type ? String(r.ticket_type).slice(0, 80) : null,
  }));
  const { data, error } = await supabase.rpc("import_players", { p_session_id: sessionId, p_rows: clean });
  if (error || !data) return { ok: false, error: error?.message ?? "The import failed." };
  revalidatePath("/admin");
  revalidatePath("/admin/players");
  return { ok: true, ...(data as Omit<Extract<ImportResult, { ok: true }>, "ok">) };
}

export type WelcomeResult = { sent: number; alreadyWelcomed: number; error: string | null };

export async function sendWelcome(sessionId: string): Promise<WelcomeResult> {
  const { supabase } = await requireAdmin();
  const [{ data: sessionRow }, { data: ticketRows }] = await Promise.all([
    supabase.from("session").select("number, neighborhood, starts_at, season:season_id (number, name)").eq("id", sessionId).single(),
    supabase.from("ticket").select("player:player_id (id, email, name, welcomed_at)").eq("session_id", sessionId),
  ]);
  const session = sessionRow as unknown as { number: number; neighborhood: string | null; starts_at: string | null; season: { number: number; name: string | null } | null } | null;
  if (!session) return { sent: 0, alreadyWelcomed: 0, error: "Session not found." };

  const players = rows<{ player: { id: string; email: string; name: string; welcomed_at: string | null } | null }>(ticketRows)
    .map((t) => t.player)
    .filter((p): p is NonNullable<typeof p> => !!p);
  const pending = players.filter((p) => !p.welcomed_at);
  if (pending.length === 0) return { sent: 0, alreadyWelcomed: players.length, error: null };

  const seasonName = session.season?.name ? `${session.season.name} ` : "";
  const ctx = {
    sessionLabel: `Colgrid ${seasonName}Session ${String(session.number).padStart(2, "0")}`,
    neighborhood: session.neighborhood,
    when: formatWhen(session.starts_at),
  };
  const targets: WelcomeTarget[] = pending.map((p) => ({ email: p.email, name: p.name }));
  const { sent, error } = await sendWelcomeEmails(targets, ctx);

  if (sent.length) {
    const sentIds = pending.filter((p) => sent.includes(p.email)).map((p) => p.id);
    await supabase.from("player").update({ welcomed_at: new Date().toISOString() }).in("id", sentIds);
  }
  revalidatePath("/admin/players");
  return { sent: sent.length, alreadyWelcomed: players.length - pending.length, error };
}

// Remove a ticket (e.g. a refund). Only before they've been checked in: once someone has played,
// their attendance, XP and badges stay (progress only goes up).
export async function removeTicket(form: FormData) {
  const { supabase } = await requireAdmin();
  const ticketId = text(form, "ticket_id", 64);
  const sessionId = text(form, "session_id", 64);
  const playerId = text(form, "player_id", 64);
  const path = `/admin/players?session=${sessionId}`;
  if (!ticketId || !sessionId || !playerId) back(path, "Missing ticket.");
  const { data: here } = await supabase.from("attendance").select("player_id").eq("session_id", sessionId).eq("player_id", playerId);
  if (rows(here).length) back(path, "They already played this session, so their ticket stays.");
  const { error } = await supabase.from("ticket").delete().eq("id", ticketId);
  revalidatePath("/admin/players");
  back(path, error ? "Couldn't remove the ticket." : "Ticket removed. Their pass stays, but they're off this session's list.");
}
